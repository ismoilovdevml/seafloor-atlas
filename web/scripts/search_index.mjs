// Search index for cables and notable wrecks: public/data/search-index.json (a few tens of kB), so focusing the search
// box no longer downloads the 3.7 MB wrecks.geojson and the cable file just to read names. Rows keep each feature's
// position in its file (the `_i` the overlay cards use), so choosing a result still opens the right feature.
// Runs before every build (package.json), after the weekly refresh has rewritten the GeoJSON files.
//   node scripts/search_index.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isNotableWreck } from '../src/overlays.ts';

const data = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'data');
const read = (f) => JSON.parse(readFileSync(join(data, f), 'utf8'));
const cables = read('cables.geojson').features
  .map((f, i) => [f.properties.name, f.properties.planned ? 1 : 0, i])
  .filter(([name]) => name);
const wrecks = read('wrecks.geojson').features
  .map((f, i) => [f.properties.name, f.properties.year ?? null, i, f.properties])
  .filter(([name, , , p]) => name && isNotableWreck(p))
  .map(([name, year, i]) => [name, year, i]);
const out = { note: 'generated by scripts/search_index.mjs from cables.geojson and wrecks.geojson; rows: [name, planned | year, feature index]', cables, wrecks };
writeFileSync(join(data, 'search-index.json'), JSON.stringify(out));
console.log(`search-index.json: ${cables.length} cables, ${wrecks.length} notable wrecks`);
