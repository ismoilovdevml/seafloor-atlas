// Writes src/lowland-index.ts: which relief tiles can hold land below sea level (coverage alpha LOW_LAND_ALPHA = 1,
// pipeline/tiles.py), so src/lowland.ts fetches the coverage tile next to a DEM tile only where it can matter.
//   low[z] (z0..maxzoom): the static coverage tile z/x/y holds alpha-1 pixels: any at maxzoom, at least
//   GLOBE_MIN_PX below it (a z0-4 tile spans thousands of km; fewer than 64 of its 262,144 pixels are a few stray
//   dots of the old shallow-sea colour on a whole-globe view, and skipping those tiles halves the extra downloads
//   there: at z3 21 instead of 45 of 64 tiles);
//   near: the z(maxzoom) tile holds alpha-1 or land (alpha 0 over a DEM height >= 0); the PMTiles zooms above are
//   looked up by their z(maxzoom) ancestor. Land below sea level always lies inside a land mass, so a small polder
//   that is below half a z5 pixel (and so not yet alpha 1 there) still falls in a "near" tile.
// The file records the tiles' content hash; test/lowland.test.ts fails when the tiles change without a rerun.
//   node scripts/lowland_index.mjs          (needs the host `dwebp`, as test/stories.test.ts)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { lowlandTileHash } from '../src/lowland-hash.ts';

const WEB = join(import.meta.dirname, '..');
const TILES = join(WEB, 'public', 'tiles');
const meta = JSON.parse(readFileSync(join(TILES, 'meta.json'), 'utf8'));
const Z = meta.maxzoom, S = meta.tileSize;
const GLOBE_MIN_PX = 64;

/** RGBA pixels of a lossless WebP tile (dwebp -> PAM). */
function pixels(file) {
  const pam = execFileSync('dwebp', ['-quiet', file, '-pam', '-o', '-'], { maxBuffer: 64 << 20 });
  const end = pam.indexOf('ENDHDR\n') + 7;
  const hdr = pam.subarray(0, end).toString();
  const w = Number(/WIDTH (\d+)/.exec(hdr)[1]), d = Number(/DEPTH (\d+)/.exec(hdr)[1]);
  if (w !== S || d !== 4) throw new Error(`${file}: width ${w}, depth ${d}`);
  return pam.subarray(end);
}
const toB64 = (bits) => {
  const bytes = new Uint8Array(Math.ceil(bits.length / 8));
  bits.forEach((b, i) => { if (b) bytes[i >> 3] |= 1 << (i & 7); });
  return Buffer.from(bytes).toString('base64');
};

const low = [];
let near = [];
for (let z = 0; z <= Z; z++) {
  const n = 2 ** z, bits = new Array(n * n).fill(false), nearBits = new Array(n * n).fill(false);
  for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
    const cov = pixels(join(TILES, 'coverage', String(z), String(x), `${y}.webp`));
    let lowPx = 0, zeroAlpha = false;
    for (let i = 3; i < cov.length; i += 4) { if (cov[i] === 1) lowPx++; else if (cov[i] === 0) zeroAlpha = true; }
    const hasLow = lowPx > 0;
    bits[y * n + x] = z === Z ? hasLow : lowPx >= GLOBE_MIN_PX;
    if (z === Z) {
      let land = hasLow;
      if (!land && zeroAlpha) {
        const dem = pixels(join(TILES, 'dem', String(z), String(x), `${y}.webp`));
        for (let i = 0; i < S * S && !land; i++) land = cov[i * 4 + 3] === 0 && dem[i * 4] * 256 + dem[i * 4 + 1] + dem[i * 4 + 2] / 256 - 32768 >= 0;
      }
      nearBits[y * n + x] = land;
    }
  }
  low.push(toB64(bits));
  if (z === Z) near = toB64(nearBits);
  console.log(`z${z}: ${bits.filter(Boolean).length} of ${n * n} tiles flagged (land below sea level${z === Z ? '' : `, >= ${GLOBE_MIN_PX} px`})`);
}
const out = `// Generated by scripts/lowland_index.mjs from web/public/tiles (do not edit). Which relief tiles can hold land below
// sea level (coverage alpha 1): one bit per tile, row-major (y * 2^z + x), least significant bit first. src/lowland.ts.
export const LOWLAND_INDEX = {
  /** meta.json hires.revision of the tile build this index was made from (the PMTiles zooms are looked up through it) */
  revision: ${JSON.stringify(meta.hires?.revision ?? null)},
  /** sha256 over the static coverage tiles and the z${Z} DEM tiles (scripts/lowland_hash.mjs) */
  sha256: '${lowlandTileHash(TILES, Z)}',
  maxzoom: ${Z},
  low: ${JSON.stringify(low)},
  near: '${near}',
};
`;
writeFileSync(join(WEB, 'src', 'lowland-index.ts'), out);
console.log('wrote src/lowland-index.ts');
