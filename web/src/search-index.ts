// The small search index (public/data/search-index.json, written by scripts/search_index.mjs) and how a chosen row
// finds its feature again. Rows carry the feature's stable `properties.id` (cable slug, Wikidata QID for wrecks),
// never its position in the file: the weekly refresh adds and removes wrecks, and a browser or CDN can hold an older
// index next to a newer GeoJSON for a while (data/* is cached for an hour plus a day of stale-while-revalidate).
// No DOM and no imports (scripts/search_index.mjs loads it with plain Node); unit-tested in test/search-index.test.ts.

type Props = Record<string, any>;
type Feature = { properties: Props | null; geometry?: unknown };
/** [name, planned (0/1) for cables | year for wrecks, stable id]. Version 1 files had the array index as the id. */
export type IndexRow = [name: string, extra: number | null, id: string | number];
export interface SearchIndexFile { version: 2; note: string; cables: IndexRow[]; wrecks: IndexRow[] }

/** `notableWreck` is isNotableWreck from overlays.ts (passed in so this file needs no import). */
export function buildSearchIndex(cables: Feature[], wrecks: Feature[], notableWreck: (p: Props) => boolean): SearchIndexFile {
  const rows = (fs: Feature[], keep: (p: Props) => boolean, extra: (p: Props) => number | null): IndexRow[] => {
    const out: IndexRow[] = [];
    for (const f of fs) {
      const p = f.properties ?? {};
      if (!p.name || !keep(p)) continue;
      if (typeof p.id !== 'string' || !p.id) throw new Error(`search index: feature "${p.name}" has no string properties.id`);
      out.push([p.name, extra(p), p.id]);
    }
    return out;
  };
  return {
    version: 2,
    note: 'generated by scripts/search_index.mjs from cables.geojson and wrecks.geojson; rows: [name, planned | year, properties.id]',
    cables: rows(cables, () => true, (p) => (p.planned ? 1 : 0)),
    wrecks: rows(wrecks, notableWreck, (p) => p.year ?? null),
  };
}

/** The feature a search row means: by stable id first, then (an id that is gone, or a version 1 index whose ids are
 *  array positions) by name, preferring the same year when several share it. Never by array position. */
export function resolveIndexed<F extends Feature>(features: F[], id: string, name: string, year?: number | null): F | undefined {
  const byId = features.find((f) => f.properties?.id === id);
  if (byId) return byId; // same ship or cable even if its label changed upstream
  const named = features.filter((f) => f.properties?.name === name);
  if (year != null) { const same = named.find((f) => f.properties?.year === year); if (same) return same; }
  return named[0];
}
