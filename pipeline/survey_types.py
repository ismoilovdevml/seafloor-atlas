"""How the measured seafloor was measured: share of the ocean per direct TID code, per GEBCO release.

Input   dataset/tables/by_tid_code_by_release.csv   (pipeline/build_dataset.py tables; fixed GEBCO_2026 ocean mask)
Output  figures/fig14_survey_types.png
        docs/survey_types.md                       (the same numbers as a table)

    python pipeline/survey_types.py
"""
from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "dataset/tables/by_tid_code_by_release.csv"
OUT_FIG = ROOT / "figures/fig14_survey_types.png"
OUT_MD = ROOT / "docs/survey_types.md"

# Direct codes drawn on their own; 12-15 are small and drawn together.
GROUPS = [
    ("Multibeam sonar (11)", (11,), "#2a78d6"),
    ("Combination of direct methods (17)", (17,), "#8fb8ea"),
    ("Single-beam sonar (10)", (10,), "#eb6834"),
    ("Optical light sensor (16)", (16,), "#f2b134"),
    ("Seismic, isolated, ENC sounding, lidar (12-15)", (12, 13, 14, 15), "#52514e"),
]


def load() -> dict[int, dict[int, float]]:
    """release -> TID code -> share of the fixed ocean mask, in percent."""
    t: dict[int, dict[int, float]] = defaultdict(dict)
    with TABLE.open() as fh:
        for r in csv.DictReader(fh):
            t[int(r["release"])][int(r["tid"])] = 100 * float(r["share_of_ocean_fraction"])
    return dict(sorted(t.items()))


def grouped(t: dict[int, dict[int, float]]) -> dict[str, list[float]]:
    return {name: [sum(t[y].get(c, 0.0) for c in codes) for y in t] for name, codes, _ in GROUPS}


def write_md(t: dict[int, dict[int, float]]) -> None:
    g = grouped(t)
    yrs = list(t)
    lines = ["# How the measured seafloor was measured", "",
             "Share of the ocean (fixed GEBCO_2026 mask, 361.7 million km²) per direct TID code in each GEBCO release.",
             "Generated by `pipeline/survey_types.py` from `dataset/tables/by_tid_code_by_release.csv`.", "",
             "| Source (TID) | " + " | ".join(str(y) for y in yrs) + " |",
             "|---|" + "---:|" * len(yrs)]
    for name, *_ in GROUPS:
        lines.append(f"| {name} | " + " | ".join(f"{v:.2f}" for v in g[name]) + " |")
    tot = [sum(t[y].get(c, 0.0) for c in range(10, 18)) for y in yrs]
    lines.append("| **All direct (10-17)** | " + " | ".join(f"**{v:.2f}**" for v in tot) + " |")
    lines += ["", "Multibeam carries almost all of the growth. TID 17 appears first in GEBCO_2020. TID 16 (optical light sensor) "
              "is negligible until 2023 and grows most in 2026. The codes say how the "
              "contributor flagged the data, not how well a cell was surveyed.", ""]
    OUT_MD.write_text("\n".join(lines))


def figure(t: dict[int, dict[int, float]]) -> Path:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    yrs = list(t)
    g = grouped(t)
    fig, ax = plt.subplots(figsize=(10, 5.6), dpi=150)
    bottom = [0.0] * len(yrs)
    for name, _, colour in GROUPS:
        ax.bar(yrs, g[name], bottom=bottom, color=colour, width=0.72, label=name, edgecolor="white", lw=0.6)
        bottom = [b + v for b, v in zip(bottom, g[name])]
    for y, tot in zip(yrs, bottom):
        ax.annotate(f"{tot:.1f}%", (y, tot), textcoords="offset points", xytext=(0, 3), ha="center", fontsize=9)
    ax.set_xticks(yrs, [f"GEBCO_{y}" for y in yrs], fontsize=8)
    ax.set_ylabel("Share of the seafloor (%)")
    ax.set_ylim(0, 35)
    ax.grid(axis="y", color="0.88", lw=0.6)
    ax.set_axisbelow(True)
    ax.spines[["top", "right"]].set_visible(False)
    handles, labels = ax.get_legend_handles_labels()
    ax.legend(handles[::-1], labels[::-1], frameon=False, loc="upper left", fontsize=8.5)
    ax.set_title("How the directly measured seafloor was measured, per GEBCO release", fontsize=12, loc="left")
    fig.text(0.5, 0.01, "Data: GEBCO Compilation Group (2019-2026) Type Identifier grids; fixed GEBCO_2026 ocean mask "
             "(361.7 M km²); table in docs/survey_types.md", ha="center", fontsize=7, color="0.35")
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    fig.savefig(OUT_FIG)
    plt.close(fig)
    return OUT_FIG


def main() -> None:
    t = load()
    write_md(t)
    print(figure(t), OUT_MD)


if __name__ == "__main__":
    main()
